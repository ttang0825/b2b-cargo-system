// 필수 항목 별표 — 34차.
//
// 🔴 **별표(기호)와 색을 둘 다 쓴다.** 색각 이상자에게는 빨강·검정 차이가 보이지
//    않으므로, 색을 빼도 별표만으로 필수임을 알 수 있어야 한다. 반대로 별표를 빼고
//    색만 남기는 변경도 하지 말 것 — 그 순간 그 사람들에게는 표시가 사라진다.
//
// 🔴 **라벨에 `*` 를 문자로 적지 말 것** — 이 컴포넌트가 유일한 표시처다. 문자로 적으면
//    색이 안 붙고, 나중에 표시를 바꿀 때 어느 화면이 남았는지 알 수 없다.
//
// 🔴 **입력칸 쪽 표시는 CSS 가 한다** — 그 칸을 감싼 `.field` 에 `field-required` 를
//    같이 주면 왼쪽 선과 옅은 바탕이 붙는다(스코프는 `.req-marks`, `app/globals.css`).

export default function RequiredMark() {
  return (
    <span className="req-star" aria-label="필수 항목" title="필수 항목">
      *
    </span>
  );
}
