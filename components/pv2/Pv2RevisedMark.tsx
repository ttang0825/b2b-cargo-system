import { QUOTE_REVISED_BADGE_LABEL } from "@/lib/quoteRevision";

// 화주포털 견적 목록의 **「수정견적」 배지** (2026-09-17 · 사용자 지시)
//
// *「한번 승인된 견적에서 견적조정으로 수정이 될때, 화주포털 견적확인 목록에서 금액 앞에
//   "수정견적" 이라고 뱃지가 붙으면 좋을 것 같다」*
//
// 🔴 **`Pv2UpdatedMark`(「업데이트」)와 다른 것이다 — 합치지 말 것.**
//    「업데이트」는 *마지막으로 본 뒤에 뭐라도 바뀐 건 전부*(신호가 `updated_at`)이고,
//    이것은 **승인한 뒤에 금액이 조정된 건**(신호가 `revised_at`)이다. 같은 카드에 둘이
//    함께 뜰 수 있고 그것이 정상이다.
//
// 🔴 **색은 새 색이 아니라 포털의 잉크(`#1A1A1A`)를 뒤집은 것이다.** 이 카드에서
//    파랑은 「업데이트」·「견적 도착」, 옅은 노랑은 「운송 확정」, 옅은 레드는 「취소」,
//    주황은 「혼적가능」이 이미 쓰고 있다 — 색을 하나 더 만들면 뜻이 흐려진다.
//    🔴 **회색으로 낮추지 말 것** — 화주가 승인한 금액이 달라졌다는 말이라 반드시 읽혀야
//       한다(사용자가 이 배지를 요청한 이유가 그것이다).
//
// 🔴 **상세보기에는 넣지 않는다**(사용자 원문: *「상세보기에는 표시가 없어도 된다」*) —
//    펼치면 조정된 금액이 항목별로 그대로 보인다.
export default function Pv2RevisedMark() {
  return (
    <span className="pv2-revised" title="승인 이후 견적 금액이 조정된 건입니다">
      {QUOTE_REVISED_BADGE_LABEL}
    </span>
  );
}
