-- ① 백업 스냅샷 — 되돌릴 유일한 수단
--    🔴 `if not exists` 라 재실행해도 **처음 값을 덮어쓰지 않습니다.**
create table if not exists _bak_rate_surcharges_before_v12 as
  select * from rate_surcharges;


-- ② 착수 단언 — 실측과 같은 모양인가
--    🔴 **현행 「값」은 단언하지 않습니다** — 값을 단언하면 재실행이 실패합니다.
do $$
declare n int;
begin
  select count(*) into n from rate_surcharges where category = '차량형태';
  if n <> 21 then raise exception '차량형태가 21행이 아니다: %행. 중단한다.', n; end if;

  select count(*) into n from rate_surcharges where category = '운송시간';
  if n <> 6 then raise exception '운송시간이 6행이 아니다: %행. 중단한다.', n; end if;

  -- 🔴 이름이 한 글자라도 다르면 그 행이 조용히 안 바뀌고, 견적에서는 가산이
  --    예외도 경고도 없이 빠진다(`option_name` 완전일치 후 continue — 20차 `도크`).
  select count(*) into n from rate_surcharges
   where category = '차량형태'
     and option_name not in ('카고', '카고/윙', '차종무관', '특수/협의', '호로', '윙바디', '윙바디/탑', '탑차', '윙플러스', '초장축', '리프트', '카고리프트', '호로리프트', '리프트윙', '탑리프트', '냉장탑', '냉장윙', '냉동탑', '냉장윙리프트', '냉동탑리프트', '무진동');
  if n <> 0 then
    raise exception '예상 밖의 차량형태 이름이 %행 있다. 실측부터 다시 할 것.', n;
  end if;

  select count(*) into n from rate_surcharges
   where category = '운송시간'
     and option_name not in ('평일 주간', '출퇴근/혼잡', '평일 야간', '주말', '공휴일', '새벽');
  if n <> 0 then
    raise exception '예상 밖의 운송시간 이름이 %행 있다. 실측부터 다시 할 것.', n;
  end if;
end $$;


