-- 차수 없음 — 운임기준표 v12 B장 (가산 요율제 → 정액 전환)
--
-- 🔴 이 파일은 GitHub Actions "DB 마이그레이션" 워크플로가 실행합니다(47차).
--    Supabase SQL Editor 에 붙여넣지 마십시오. 워크플로가 파일 전체를
--    --single-transaction 으로 감싸므로 begin;/commit; 을 쓰지 않습니다.
--
-- 🔴 **A장(`2026-09-15_rate_v12_a.sql`)이 먼저 반영돼 있어야 합니다.**
--    B 가 먼저 들어가도 깨지지는 않지만, C(소계 반올림)가 B 보다 먼저 들어가면
--    **아직 요율제인 가산을 반올림해 중간 상태의 견적이 실제보다 올라갑니다.**
--
--
-- ── 🔴 왜 정액인가 (사용자 확정 2026-09-15) ───────────────────────────
--
--   *"가산기준도 요율보다 고정가산으로 정리하자. 그리고 차량형태에 따른 고정가산도
--     현실기반으로 탑차, 윙바디, 호로, 리프트 등에 적용하자. 가산이 필요없는
--     차량형태도 정하자."*
--
--   요율제가 대형·장거리에서 실측을 크게 넘었습니다. 윙바디 15% 는 1톤 10km 에서
--   6,000원인데 **25톤 400km 에서 136,500원**인 반면, 실측 차액은 차급과 무관하게
--   **약 10,000원**입니다. 시간 할증도 같습니다 — 25톤 400km 새벽 상차에 273,000원을
--   얹을 근거가 없고, 오히려 **장거리는 새벽 상차가 표준**이라 프리미엄이 거의 없습니다.
--
--   🔴 **근거는 실측 「절대 차액(원)」입니다** — 같은 차급 × 같은 거리구간의 카고
--      중앙값 대비. 윙바디 10,000(145건) · 리프트 15,000(35건) · 냉동탑 50,000(10건) ·
--      카고계열 0(722건).
--
--
-- ── 🔴 요소 정액 — 가법 구조 ──────────────────────────────────────────
--
--     윙 · 호로 (개폐·덮개)    10,000
--     탑 (밀폐)               20,000
--     리프트 (파워게이트)       20,000
--     초장축                  20,000
--     냉장                    40,000
--     냉동                    50,000
--     무진동                 100,000
--     🔴 조합형(`카고/윙` · `윙바디/탑`)은 **낮은 쪽**을 따릅니다
--
--
-- ── 🔴 가산이 0원인 넷은 의도다 (행을 지우지 말 것) ───────────────────
--
--     카고        실측 차액 0원 (428건)
--     카고/윙      실측 차액 0원 ( 69건)   조합형이라 배차가 더 쉽습니다
--     차종무관      실측 차액 0원 (225건)   제약이 없어 가장 쉽습니다
--     특수/협의     건별 협의               금액을 미리 못 정합니다
--
--   🟢 **전체 오더의 71%** 가 이 넷입니다.
--   🔴 **「0원이면 행을 지우자」고 하지 마십시오** — 행이 없으면 `option_name`
--      문자열 완전일치에 실패해 **드롭다운에서 고를 수 없게** 됩니다(20차 `도크`).
--
--   🔴 **대형은 윙바디 프리미엄이 없습니다** — 차급군별 실측 차액이 소형 5,000 ·
--      중형 25,000 · **준대형 −5,000 · 대형 −10,000** 입니다. 큰 차는 윙바디가
--      표준이라 프리미엄이 붙지 않습니다. 🔴 **「대형인데 왜 가산이 같지」로
--      요율을 되살리지 마십시오.**
--
--
-- ── 차량형태 21행 (근거 등급 A = 표본 69건 이상 · B = 10~35 · C = 4~5 · D = 1~2 또는 유도값)
--
--     카고                           0% →       0   실측       0  표본 428  A   기준
--     카고/윙                         0% →       0   실측       0  표본  69  A   조합형 — 낮은 쪽
--     차종무관                         0% →       0   실측       0  표본 225  A   제약 없음
--     특수/협의                        0% →       0   실측       —  표본   0  D   건별 협의
--     호로                           5% →  10,000   실측   5,000  표본   1  D   덮개 10,000
--     윙바디                         15% →  10,000   실측  10,000  표본 145  A   개폐 10,000
--     윙바디/탑                       10% →  10,000   실측       —  표본   0  D   조합형 — 낮은 쪽
--     탑차                          10% →  20,000   실측  40,000  표본   5  C   밀폐 20,000
--     윙플러스                        20% →  20,000   실측       —  표본   0  D   윙 10,000 + 상위 10,000
--     초장축                20% + 30,000 →  20,000   실측  10,000  표본   5  C   장척 20,000
--     리프트                20% + 30,000 →  20,000   실측  15,000  표본  35  B   파워게이트 20,000
--     카고리프트              20% + 30,000 →  20,000   실측       —  표본   0  D   카고 0 + 리프트 20,000
--     호로리프트              25% + 30,000 →  30,000   실측       —  표본   0  D   호로 10,000 + 리프트 20,000
--     리프트윙               30% + 30,000 →  30,000   실측  60,000  표본   4  C   윙 10,000 + 리프트 20,000
--     탑리프트               25% + 30,000 →  40,000   실측  80,000  표본   2  D   탑 20,000 + 리프트 20,000
--     냉장탑                25% + 30,000 →  40,000   실측  95,000  표본   5  C   냉장 40,000
--     냉장윙                30% + 30,000 →  50,000   실측       —  표본   0  D   냉장 40,000 + 윙 10,000
--     냉동탑                35% + 50,000 →  50,000   실측  50,000  표본  10  B   냉동 50,000
--     냉장윙리프트             45% + 50,000 →  70,000   실측       —  표본   0  D   냉장윙 50,000 + 리프트 20,000
--     냉동탑리프트             45% + 50,000 →  70,000   실측       —  표본   0  D   냉동탑 50,000 + 리프트 20,000
--     무진동               50% + 100,000 → 100,000   실측       —  표본   0  D   무진동 100,000
--
--
-- ── 운송시간 6행 ──────────────────────────────────────────────────────
--
--   현행 실효액은 (1톤 10km / 5톤 60km / 25톤 400km 초과) 기준입니다.
--
--     평일 주간              – →      0    현행 실효액 0 / 0 / 0
--     출퇴근/혼잡           10% → 10,000    현행 실효액 4,000 / 15,000 / 91,000
--     평일 야간            10% → 10,000    현행 실효액 4,000 / 15,000 / 91,000
--     주말               10% → 10,000    현행 실효액 4,000 / 15,000 / 91,000
--     공휴일              10% → 10,000    현행 실효액 4,000 / 15,000 / 91,000
--     새벽               30% → 20,000    현행 실효액 12,000 / 45,000 / 273,000
--
--   🔴 **새벽은 20,000 입니다** — 기획 세션이 30,000 으로 유도했으나 **사용자가
--      *「새벽의 비율이 너무 높다」*로 낮췄습니다.** 🔴 **30,000 으로 되돌리지 마십시오.**
--      다른 시간 할증의 2배이고, 현행 요율 비(3배)에서 줄인 것입니다.
--   ⚠️ 🔴 **실측 표본 0건입니다** — 수집 오더 1,860건이 전부 **06~19시**라 새벽·야간·
--      주말 건이 없습니다. **근거 등급 D 이고 「실측으로 확인됐다」고 적지 마십시오.**
--
--
-- ── 🔴 이번에 손대지 않는 것 ──────────────────────────────────────────
--
--   `왕복/편도`   **3행** — `왕복` 0.8 · `편도` 0 · `회수/재방문` 0.5.
--                 🔴 **유일하게 요율을 남기는 항목**입니다. 거리에 비례하는 값이라
--                 정액으로 담을 수 없습니다(1톤 10km +4만 vs 25톤 400km +91만).
--                 ⚠️ 지시서는 2행으로 적었지만 **실측은 3행**입니다.
--   `물품특성`     8행 · `상하차방식` 8행 — 부록 B 로 미뤘습니다(별도 차수).
--                 🟢 **상하차방식은 이미 사실상 정액**입니다(요율 0건 · `수작업` 10,000 뿐).
--   `긴급여부`     4행 — **폐지된 항목**이고 화면·계산에서 빠져 있습니다(행만 보존).
--   `특별할인`     1행 `첫거래지원(10%)` rate_pct **−0.1** — 계산 `selections` 에
--                 없어 안 걸립니다. ⚠️ **지시서에 한 줄도 없던 카테고리**입니다.
--                 🔴 **셋 다 사용자 확정으로 손대지 않습니다.**
--
--
-- ── ⚠️ 가산 수입이 줄어듭니다 ─────────────────────────────────────────
--
--   건당 12,082 → 4,077원(**−66%**) · 견적 총액 −5.9% · 마진 34.5% → 26.7%.
--   🔴 **의도한 것입니다** — 배차가 오히려 쉬워지는지 운영해 보고 판단합니다.
--
--
-- ── 🔴 되돌리기 ──────────────────────────────────────────────────────
--   가산 이력 표가 없습니다. ① 이 만드는 백업 스냅샷이 되돌릴 유일한 수단이고,
