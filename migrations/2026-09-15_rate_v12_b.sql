-- ⑤ 단언 — 요율이 사라졌고 값이 표와 같으며 상하위 역전이 없다
do $$
declare n int; r record;
begin
  select count(*) into n from rate_surcharges
   where category in ('차량형태','운송시간') and coalesce(rate_pct, 0) <> 0;
  if n <> 0 then raise exception '요율이 남은 행이 %행 있다', n; end if;

  -- 🔴 값이 위 표와 한 칸이라도 다르면 멈춘다 (이름 불일치도 여기서 걸린다)
  select count(*) into n from rate_surcharges t
    join (values
    ('카고', 0),
    ('카고/윙', 0),
    ('차종무관', 0),
    ('특수/협의', 0),
    ('호로', 10000),
    ('윙바디', 10000),
    ('윙바디/탑', 10000),
    ('탑차', 20000),
    ('윙플러스', 20000),
    ('초장축', 20000),
    ('리프트', 20000),
    ('카고리프트', 20000),
    ('호로리프트', 30000),
    ('리프트윙', 30000),
    ('탑리프트', 40000),
    ('냉장탑', 40000),
    ('냉장윙', 50000),
    ('냉동탑', 50000),
    ('냉장윙리프트', 70000),
    ('냉동탑리프트', 70000),
    ('무진동', 100000)
    ) as v(nm, f) on v.nm = t.option_name
   where t.category = '차량형태' and coalesce(t.flat_amount, -1) <> v.f;
  if n <> 0 then raise exception '차량형태 정액이 표와 다른 행이 %행 있다', n; end if;

  select count(*) into n from rate_surcharges t
    join (values
    ('평일 주간', 0),
    ('출퇴근/혼잡', 10000),
    ('평일 야간', 10000),
    ('주말', 10000),
    ('공휴일', 10000),
    ('새벽', 20000)
    ) as v(nm, f) on v.nm = t.option_name
   where t.category = '운송시간' and coalesce(t.flat_amount, -1) <> v.f;
  if n <> 0 then raise exception '운송시간 정액이 표와 다른 행이 %행 있다', n; end if;

  -- 🔴 전부 10,000 배수여야 C장 반올림이 최종금액을 만원으로 만든다
  select count(*) into n from rate_surcharges
   where category in ('차량형태','운송시간') and coalesce(flat_amount, 0) % 10000 <> 0;
  if n <> 0 then raise exception '10,000 배수가 아닌 정액이 %행 있다', n; end if;

  -- 🔴 가산 0원 4종의 **행이 남아 있어야** 한다 (지우면 드롭다운에서 못 고른다)
  select count(*) into n from rate_surcharges
   where category = '차량형태'
     and option_name in ('카고','카고/윙','차종무관','특수/협의')
     and coalesce(flat_amount, -1) = 0;
  if n <> 4 then raise exception '가산 0원 4종이 4행이 아니다: %행', n; end if;

  -- 🔴 상하위 역전 — 요소를 더한 쪽이 반드시 더 비싸야 한다
  for r in select * from (values
    ('카고', '호로'),
    ('호로', '호로리프트'),
    ('탑차', '탑리프트'),
    ('윙바디', '리프트윙'),
    ('냉장탑', '냉동탑'),
    ('냉장탑', '냉장윙'),
    ('냉장윙', '냉장윙리프트'),
    ('냉동탑', '냉동탑리프트'),
    ('카고', '카고리프트'),
    ('윙바디', '냉장윙'),
    ('리프트', '탑리프트'),
    ('윙바디', '윙플러스')
  ) as p(lo, hi) loop
    select count(*) into n from rate_surcharges a
      join rate_surcharges b
        on b.category = '차량형태' and b.option_name = r.hi
     where a.category = '차량형태' and a.option_name = r.lo
       and coalesce(b.flat_amount, 0) <= coalesce(a.flat_amount, 0);
    if n <> 0 then
      raise exception '상하위 역전: % 가 % 보다 싸지 않다', r.hi, r.lo;
    end if;
  end loop;

  -- 🔴 범위 밖 카테고리는 한 칸도 안 바뀌어야 한다
  select count(*) into n from rate_surcharges
   where category = '왕복/편도'
     and (option_name, rate_pct) not in (('왕복', 0.8), ('편도', 0.0), ('회수/재방문', 0.5));
  if n <> 0 then raise exception '`왕복/편도` 요율이 바뀌었다: %행', n; end if;

  select count(*) into n from rate_surcharges where category = '물품특성';
  if n <> 8 then raise exception '`물품특성` 행수가 8이 아니다: %', n; end if;

  select count(*) into n from rate_surcharges where category = '상하차방식';
  if n <> 8 then raise exception '`상하차방식` 행수가 8이 아니다: %', n; end if;

  select count(*) into n from rate_surcharges where category = '긴급여부';
  if n <> 4 then raise exception '`긴급여부` 행수가 4가 아니다: %', n; end if;

  select count(*) into n from rate_surcharges where category = '특별할인';
  if n <> 1 then raise exception '`특별할인` 행수가 1이 아니다: %', n; end if;

  select count(*) into n from rate_surcharges;
  if n <> 51 then raise exception '`rate_surcharges` 총행수가 51이 아니다: %행', n; end if;
end $$;


-- ⑥ 반영 결과 (로그로 눈에 보이게)
select category as 카테고리, option_name as 항목, rate_pct as 요율, flat_amount as 정액
  from rate_surcharges
 where category in ('차량형태','운송시간')
 order by category, flat_amount, option_name;


