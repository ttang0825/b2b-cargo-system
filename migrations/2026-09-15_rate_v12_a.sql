--   🔴 **앵커는 `1톤 10km 이내 = 40,000` 하나**입니다 — 반올림 대상이 아니라
--      사용자가 확정한 공개 게시가입니다. 건드리지 마십시오.
--
--
-- ── 🔴 10·20·30km 만 내렸다 · 60km 이상은 격자 정렬만 ────────────────
--
