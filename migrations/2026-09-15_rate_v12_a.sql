-- ── 🔴 왜 하는가 (사용자 확정 2026-09-15) ─────────────────────────────
--
--   *"운임기준표에서 견적금액이 만원단위로 떨어졌으면 좋겠다. 고객 입장에서
--     부가세 계산도 불편하고 천원단위, 백원 단위가 있으면 정산계산이 불편할것 같다."*
--   *"다마스,라보만 기본 견적이 35,000원으로 5000원 단위만 허용하자."*
--   *"2.5톤은 80,000원 / 3.5톤은 90,000원 / 5톤은 110,000원 / 5톤+는 140,000원으로 조정"*
--
--   ① 고객이 보는 최종 견적금액을 만원 단위로 만들기 위해 **기본운임부터 격자에 올립니다.**
--   ② 중형 4차급의 근거리 기본가가 실측 대비 마진 33~56% 로 과했습니다.
--
--   🔴 **이것은 A장뿐입니다.** B장(가산 정액 전환)과 C장(소계 반올림)이 뒤따르고,
--      **C 가 먼저 들어가면 아직 요율제인 가산을 반올림해 중간 상태의 견적이 올라갑니다.**
--      A → B → C 순서를 바꾸지 마십시오.
--
--
-- ── 🔴 `base_fare` 는 화주 청구가다 (v11 과 같다) ─────────────────────
--
--   마진율 파라미터는 시스템에 없습니다. 차주 지급가는 배차 담당자가 건별로 넣고
--   마진은 그 차액입니다(`lib/marginCalc.ts`). 🔴 **마진율 컬럼·설정 화면을 만들지
--   마십시오** — 만드는 순간 `base_fare` 의 의미가 뒤집혀 공개 게시가에 원가가 나갑니다.
--
--   🔴 **v10 매트릭스로 마진을 재지 마십시오.** 근거리 값이 「완료·독차·30km 초과
--      527건」 계수의 **외삽**이라 실측보다 40% 이상 높습니다. 기획 세션이 그것으로
--      재서 *「3.5톤 90,000 은 마진 3.4%」*라는 틀린 경고를 냈고, 실측으로 다시
--      재니 **50%** 였습니다. 마진은 **24시콜 실거래(완료·독차) 중앙값**으로 잽니다.
--
--
-- ── 🔴 격자가 둘이다 (한 격자로 합치지 말 것) ─────────────────────────
--
--     다마스 · 라보      5,000 배수
--     1톤 이상          10,000 배수
--
--   전 차급을 만원으로 단순 반올림하면 **역전 17건**이 납니다 — 라보 35,000 과
--   1톤 40,000 이 둘 다 40,000 이 되고, 11·15·18톤 200km(342·344·345천)가
--   셋 다 340,000 이 됩니다. 🔴 **`200km 이내` 는 차급 간격이 가장 좁은 구간**
--   이라(HANDOFF §5-1) 값을 만질 때 거기부터 역전을 보십시오.
