  end if;

  select count(*) into n from rate_distance_tiers where base_fare is null or base_fare <= 0;
  if n <> 0 then raise exception '값이 없거나 0 이하인 행이 %행 있다', n; end if;

  -- 🔴 격자가 둘이다 — 한 격자로 합치지 말 것(위 머리말)
  select count(*) into n from rate_distance_tiers
   where vehicle_type not in ('다마스','라보') and base_fare % 10000 <> 0;
  if n <> 0 then raise exception '1톤 이상인데 만원 배수가 아닌 행이 %행 있다', n; end if;

  select count(*) into n from rate_distance_tiers
   where vehicle_type in ('다마스','라보') and base_fare % 5000 <> 0;
  if n <> 0 then raise exception '다마스·라보인데 5,000 배수가 아닌 행이 %행 있다', n; end if;

  -- 🔴 앵커 — 사용자 확정값이다
  select base_fare into n from rate_distance_tiers
   where vehicle_type = '1톤' and distance_label = '10km 이내';
  if n <> 40000 then raise exception '1톤 10km 가 40,000 이 아니다: %', n; end if;

  -- 🔴 공개 게시가 6칸 — 랜딩이 이 값을 실시간으로 읽는다. 어긋나면 멈춘다.
  select count(*) into n from rate_distance_tiers t
    join (values ('1톤',40000),('1.4톤',50000),('2.5톤',80000),
                 ('3.5톤',90000),('5톤',110000),('5톤 플러스/축',140000)) as p(vt,f)
      on p.vt = t.vehicle_type
   where t.distance_label = '10km 이내' and t.base_fare <> p.f;
