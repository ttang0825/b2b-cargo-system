    raise exception '예상 밖의 차급명이 %행 있다. 실측부터 다시 할 것.', n;
  end if;

  select count(*) into n from rate_distance_tiers
   where distance_label not in ('10km 이내', '20km 이내', '30km 이내', '60km 이내', '90km 이내', '110km 이내', '130km 이내', '150km 이내', '170km 이내', '200km 이내', '250km 이내', '300km 이내', '350km 이내', '400km 이내', '400km 초과');
  if n <> 0 then
    raise exception '예상 밖의 구간명이 %행 있다. 실측부터 다시 할 것.', n;
  end if;
end $$;


