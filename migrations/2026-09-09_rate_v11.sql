-- 🔴 이 파일은 GitHub Actions "DB 마이그레이션" 워크플로가 실행합니다(47차).
--    Supabase SQL Editor 에 붙여넣지 마십시오. 워크플로가 파일 전체를
--    --single-transaction 으로 감싸므로 begin;/commit; 을 쓰지 않습니다.
--
--
-- ── 🔴 `base_fare` 는 화주 청구가다 (v10 매트릭스를 그대로 넣지 말 것) ──
--
--   근거 자료 `위캐리_운임기준표_v10` 의 매트릭스는 **차주 지급 기준**이고,
--   이 표의 `base_fare` 는 **화주 청구가**입니다. v10 값을 그대로 넣으면
--   **마진이 0** 이 됩니다(1톤 10km 이 36,000 으로 내려앉습니다).
--   v11 = ROUND(차주지급 × 1.15, -3) 이고, 이 파일의 값은 그 계산 결과입니다.
--
--   🔴 **마진 15% 는 시스템 파라미터가 아닙니다.** DB 에는 청구가만 있고 차주
--      지급가는 배차 담당자가 건별로 입력합니다. 마진율 컬럼·설정 화면을 만들지
--      마십시오 — 만드는 순간 `base_fare` 의 의미가 뒤집혀 공개 게시가에
--      **원가가 그대로 나갑니다**(랜딩 「요금 가이드」 모달이 이 표를 실시간으로 읽습니다).
--
--
-- ── 🔴 1톤 10km 40,000 은 유일한 예외다 (되돌리지 말 것) ──────────────
--
--   36,000 × 1.15 = 41,400 → 41,000 이어야 하는데 **40,000 으로 둡니다.**
--   ① 이미 공개 게시된 금액이라 올리면 인상으로 읽힙니다.
--   ② 근거리 구간은 v10 이 「30km 초과 527건」으로 낸 계수를 외삽한 값이라
--      근거가 약한 쪽입니다(아래 관찰 대상).
--   마진이 이 칸만 11.1% 입니다. 18톤 '200km 이내' 한 칸이 다른 것과 같은 성격이니
--   ⚠️ **「왜 이 칸만 다르지」 하고 ×1.15 로 맞추지 마십시오.**
--
--
-- ── ⚠️ 관찰 대상 (이번에 고치지 않는다) ──────────────────────────────
--
--   • 근거리 3구간(10/20/30km) — v10 §5 의 근거리 실측은 서울 1톤 ~30km 중앙
--     50,000(107건) · 경기 40,000(44건) 으로 **지역 편차가 25%** 입니다.
--     단일값으로 잡기 어렵고, 내리면 그 구간 배차가 막힙니다.
--   • 8톤·15톤 — v10 에 없어 인접 보간입니다(8톤 = (5톤+/축+11톤)/2 ·
--     15톤 = (11톤+18톤)/2). 등급 D 이고 15톤은 완료 표본 1건입니다.
--   • 대형 18~25톤 — 30km 초과 완료·독차 표본이 10건뿐입니다.
--
--
-- ── ⚠️ 직전 구간 대비 +25% 를 넘는 6칸은 정상이다 ────────────────────
--
--     1톤   10→20km    40,000 →  52,000  +30%   ← 위 40,000 고정 때문
