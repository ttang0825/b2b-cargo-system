-- 17차 — rate_distance_tiers에 대형 3차급(11·18·25톤) 45행 INSERT
--
-- 🔴 이 파일은 사용자가 Supabase SQL Editor에서 직접 실행합니다.
--    세션(Claude Code)이 실행하지 않았습니다.
--
-- ⚠️ 0~3단계를 **한 번에 실행하지 말고 순서대로 하나씩** 실행하십시오.
--    Supabase SQL Editor는 여러 문장을 한 번에 돌리면 마지막 결과만 보여주는 경우가
--    있어서, 2단계의 "반영된_행수 = 45"를 놓치게 됩니다(16차에서 확정한 형태).
--
-- 🔴 되돌리기가 없습니다. 운임기준표에는 이력 테이블이 없습니다.
--    다만 이번은 UPDATE가 아니라 **INSERT만** 하므로 기존 6차급 90행은 건드리지 않습니다.
--    잘못 들어가면 `where vehicle_type in ('11톤','18톤','25톤')` 으로 지우면 됩니다.
--
-- ⚠️ 차급 문자열은 `"11톤"` · `"18톤"` · `"25톤"` 입니다. `lib/constants.ts`의
--    `VEHICLE_TYPES_ALL`과 **완전일치**해야 합니다 — 견적 자동산출이 문자열 완전일치로
--    매칭하므로 한 글자만 달라도 그 차급 계산 패널이 통째로 사라집니다.
--
-- ⚠️ `400km 초과` 행의 `distance_to_km`은 **null** 입니다. 15차 매칭이
--    `distance_to_km === null`을 "상한 없는 마지막 구간"으로 처리하므로,
--    여기가 틀리면 대형 장거리 견적이 실패합니다.
--
--
-- 🔴 값의 근거 등급이 낮습니다 — 반드시 읽으십시오
--
--   11톤 · 25톤   등급 C   전국레츠고화물 공개표 **단일 출처**
--   18톤          등급 D   11톤·25톤 사이 **보간**(위치계수 0.70). **직접 근거 0건**
--
--   2026-08-25 실거래 42건 대조에서 대형 표본은 **2건뿐**이었습니다
--   (18톤 45.1km 200,000원 / 11톤 50.3km 180,000원 — 둘 다 마진 20% 이상).
--   방향은 맞지만 15구간을 검증하기에는 턱없이 얇습니다.
--
--   🔴 **대형 3종은 자동견적 결과를 참고값으로 다루고 담당자가 확인할 것.**
--   실거래가 쌓이면 재조정 대상입니다.
--
-- 산출식: 16차와 동일 — `v8 3장 매트릭스 × 1/0.83`(마진 17%), 천원 반올림.
