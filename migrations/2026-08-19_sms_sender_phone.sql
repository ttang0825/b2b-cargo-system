-- 35차 세션(10차 지시서): 담당자별 SMS 발신번호
--
-- ⚠️ 이 저장소는 지금까지 마이그레이션 파일 없이 사용자가 Supabase SQL Editor에서
-- 직접 실행해 왔다(CLAUDE.md 참고). 이 파일은 **실행 기록을 남기기 위한 것**이며,
-- 실제 적용은 사용자가 Supabase SQL Editor에서 아래를 실행해야 한다.

-- 1) 직원별 SMS 발신번호
--
-- ⚠️ **직원 연락처(내부 관리용)와는 다른 개념이다.** 이 번호는 고객에게 노출되고
-- 솔라피에 발신번호로 **사전 등록**되어 있어야 실제 발송이 된다. 등록되지 않은
-- 번호를 넣으면 발송이 실패하므로(한국은 발신번호 사전등록제), 값을 채우는 것과
-- 솔라피 등록은 항상 같이 가야 한다.
--
-- 형식: 하이픈 없이 숫자만 (예: '01012345678'). 화면 표시와 문자 본문에서만 하이픈을 붙인다.
-- null 허용 — 비어 있으면 대표 발신번호(SOLAPI_SENDER_PHONE 환경변수)로 발송된다.
alter table staff_accounts
  add column if not exists sms_sender_phone text;

-- 2) 실제로 어느 번호로 나갔는지 기록
--
-- 지시서 3-2는 "담당자 번호로 실패하면 대표번호로 재발송하고 그 사실을 로그로 남길 것"을
-- 요구한다. 실패 사유는 error_message에 남길 수 있지만, **성공한 발송이 어느 번호로
-- 나갔는지**는 남길 곳이 없어 "왜 이 고객에게는 회신이 담당자한테 안 갔지"를 나중에
-- 추적할 수 없다. 그래서 실제 사용된 발신번호를 별도 컬럼으로 남긴다(숫자만 저장).
alter table sms_logs
  add column if not exists sender_phone text;
