--
-- 🔴 이 파일은 사용자가 Supabase SQL Editor에서 직접 실행합니다.
--    세션(Claude Code)이 실행하지 않았습니다. 이 저장소의 관례이며,
--    실행 환경에 Supabase 자격증명이 없는 것이 정상입니다(44차 확인).
--
-- 🔴 되돌리기가 없습니다. 이 저장소의 운임기준표에는 이력 테이블이 없고
--    (`settlement_field_change_logs`·`invoice_amendment_logs`는 정산 전용입니다),
--    `/admin/rates`의 일괄 적용은 100원 단위 반올림이 들어가 같은 비율로 역산해도
--    원값이 복구되지 않습니다. **실행 전에 CSV export를 따로 받아두십시오.**
--    아래 1단계의 스냅샷 테이블은 그 보완일 뿐 CSV를 대신하지 않습니다.
--
-- ⚠️ 아래 1~3단계를 **한 번에 실행하지 말고 순서대로 하나씩** 실행하십시오.
--    Supabase SQL Editor는 여러 문장을 한 번에 돌리면 마지막 결과만 보여주는 경우가
--    있어서, 2단계의 "반영된_행수 = 90"을 놓치게 됩니다.
--
-- 배경 — 지금 장거리는 역마진입니다
--
--   `rate_distance_tiers.base_fare`는 **화주 청구가**이고(차주 지급가가 아님),
--   견적 계산(`app/admin/quotes/page.tsx`의 `calc`)에는 **마진율 파라미터가 없습니다**
--   — `기본운임 + 가산 − 혼적할인`이 전부입니다. 그래서 마진을 확보하는 방법은
--   `base_fare` 자체를 올리는 것뿐입니다.
--
--   실측 차주 지급 시세와 대조하면 1톤 351~400km 구간이 화주 청구 200,000 /
--   차주 지급 240,000 으로 **건당 약 40,000원 손해**였습니다.
--
--   지금이 가장 싼 시점입니다 — quotes 2건, portal_order_requests 0건이라
--   인상을 통보해야 할 기존 화주가 없습니다.
--
-- 산출식: 운임기준표 v8 3장 매트릭스 × 1/0.83(마진 17%), 천원 반올림.
--         마진율 17%는 사용자 결정(2026-08-25)이며 v8 4장 "화주 청구 참고표"와 일치합니다
--         (1톤 60km 84,000 / 1톤 400km 289,000).
--
-- 인상 폭: 10~300km +20~21% / 350km 이내 +32~33% / 400km 이내·초과 +45%
--          장거리가 큰 이유는 그 구간이 지금 역마진이기 때문입니다.
--
-- ⚠️ `distance_label` **문자열**로 매칭합니다(`distance_from_km` 숫자가 아닙니다).
--    사람이 읽을 수 있어 검토가 쉽기 때문입니다. 라벨이 하나라도 다르면 그 행이
--    **조용히 안 바뀝니다.**
--
-- ⚠️ 차급 문자열은 `5톤 플러스/축`(슬래시)입니다. 가운뎃점(`·`)이 아닙니다.
--    견적 자동산출이 `t.vehicle_type === form.vehicle_type` 완전일치로 매칭하므로
--    한 글자만 달라도 그 차급의 계산 패널이 통째로 사라집니다.


