// 24시콜 가져오기 ⓐ — 배차된 차주 정보 붙여넣기 (37차)
//
// 🔴 **이 파일이 유일한 정의처다.** 화면에서 문자열을 다시 가르지 말 것.
// 🔴 **의존성 0이다** — 순수 함수라 시험하기 쉽고, 다른 화면이 써도 된다.
//
//
// ── 🔴 무엇을 붙여넣는가 (사용자 확정 2026-09-16) ─────────────────────
//
//   *"「(차주명) (차량번호) (연락처)」 앞으로 이정도 정보만 붙여 넣겠다."*
//   ⚠️ **사용자 원문에는 실제 차주 정보가 들어 있어 가려 적었다** — 이 저장소는 public 이고,
//      아래 예시·오류 문구·placeholder 도 전부 **가짜 값**이다. 🔴 실제 값으로 바꾸지 말 것.
//
//   **한 줄 · 공백 구분 · 값 셋**이다. 🔴 **라벨이 없다.**
//
//   ⚠️ **처음엔 24시콜 목록 행(헤더 + 데이터 · 탭 40열)을 받도록 만들었다가 이 형식으로
//      바꿨다.** 목록 행 방식은 **더 이상 지원하지 않는다** — 붙여넣으면 칸이 너무 많다고
//      알리고 이 형식을 안내한다. 🔴 **「이왕이면 목록 행도」로 되살리지 말 것**(값이
//      40개라 전화번호가 여럿이고, 잘못 집으면 **엉뚱한 사람에게 문자가 나간다**).
//
//
// ── 🔴 라벨이 없으니 「모양」으로 가른다 ───────────────────────────────
//
//   순서를 믿지 않는다. 담당자가 `010-1234-5678 홍길동 서울12가3456` 로 적어도 같은
//   결과가 나와야 한다 — 사람이 손으로 옮겨 적는 값이라 순서가 흔들린다.
//
//     연락처   숫자만 남겼을 때 **10~11자리이고 0으로 시작**  (`010-1234-5678`)
//              🔴 대표번호(`1661-2403` · 8자리)는 여기 안 걸린다
//     차량번호  `(지역 0~2자)(숫자 2~3)(한글 1)(숫자 4)`        (`서울12가3456` · `12가3456`)
//     이름     위 둘이 아닌 **첫 토큰**
//
//   🔴 **애매한 것을 조용히 버리지 말 것**(원칙 55번) — 어느 것으로도 안 읽힌 토큰은
//      `unknownTokens` 로 돌려주고 화면이 보여준다.
//
//
// ── 🔴 서버에 보내지 않는다 ───────────────────────────────────────────
//
//   붙여넣은 텍스트는 **브라우저에서 갈라 입력칸에 넣고 버린다.** 서버로 보내지도
//   저장하지도 않으므로 **처리방침 변경 0 · 개인정보 보관 0** 이다(설계 v4 확정).
//   🔴 **「서버에서 파싱하자」로 바꾸면 그 성질이 통째로 사라진다.**

/** 🔴 토큰이 이보다 많으면 24시콜 목록 행을 통째로 붙여넣은 것으로 본다 */
const MAX_TOKENS = 8;

/**
 * 한국 차량번호.
 * 🔴 지역명(`경기`·`서울`)은 **있을 수도 없을 수도** 있다 — 신형은 `12가3456` 이다.
 * 🔴 가운데 한글 한 글자는 영업용(`아`·`바`·`사`·`자`·`배`)·렌터카(`허`·`하`·`호`)까지
 *    포함하므로 목록으로 가두지 않는다.
 */
const PLATE_RE = /^[가-힣]{0,2}\d{2,3}[가-힣]\d{4}$/;

/** 🔴 숫자만 남겨 10~11자리이고 0으로 시작하는 것만 연락처로 본다 */
function looksLikePhone(token: string): boolean {
  if (!/^[\d-]+$/.test(token)) return false;
  const digits = token.replace(/\D/g, "");
  return (digits.length === 10 || digits.length === 11) && digits.startsWith("0");
}

export type W24Driver = {
  name: string;
  /** 하이픈 포맷은 화면이 입힌다 — 이 파일은 의존성 0을 지킨다 */
  phone: string;
  vehiclePlate: string;
};

// 🔴 **판별자가 참/거짓이 아니라 문자열인 것은 의도다.** 이 저장소는 `strict: false`
//    라 boolean 으로는 **타입이 좁혀지지 않아** 컴파일 에러가 난다(32차가 같은 자리에서
//    겪었고 이번에도 `tsc` 가 실제로 잡았다). 🔴 **되돌리지 말 것.**
export type W24ParseResult =
  | {
      kind: "ok";
      driver: W24Driver;
      /** 어느 것으로도 안 읽힌 토큰 — 🔴 화면에 반드시 보여줄 것 */
      unknownTokens: string[];
    }
  | { kind: "error"; reason: string };

export function parseWecarry24Driver(input: string): W24ParseResult {
  // 🔴 탭·줄바꿈도 공백처럼 본다 — 어디서 복사해 오든 토큰만 뽑으면 된다
  const tokens = (input || "").split(/\s+/).filter((t) => t.length > 0);

  if (tokens.length === 0) {
    return { kind: "error", reason: "붙여넣은 내용이 비어 있습니다." };
  }
  if (tokens.length > MAX_TOKENS) {
    return {
      kind: "error",
      reason:
        "값이 너무 많습니다. 24시콜 목록 행을 통째로 붙여넣으면 어느 번호가 차주 것인지 " +
        "가릴 수 없어 받지 않습니다. 「홍길동 서울12가3456 010-1234-5678」 처럼 " +
        "차주 이름·차량번호·연락처만 붙여넣어 주세요.",
    };
  }

  let name = "";
  let phone = "";
  let plate = "";
  const unknown: string[] = [];

  for (const t of tokens) {
    if (!phone && looksLikePhone(t)) {
      phone = t;
    } else if (!plate && PLATE_RE.test(t)) {
      plate = t;
    } else if (!name && !looksLikePhone(t) && !PLATE_RE.test(t)) {
      // 🔴 전화·차량번호가 아닌 **첫 토큰**이 이름이다
      name = t;
    } else {
      unknown.push(t);
    }
  }

  if (!name && !phone) {
    return {
      kind: "error",
      reason:
        "차주 이름과 연락처를 찾지 못했습니다. 「홍길동 서울12가3456 010-1234-5678」 " +
        "처럼 붙여넣어 주세요.",
    };
  }
  if (!phone) {
    return {
      kind: "error",
      reason:
        "연락처를 찾지 못했습니다(휴대전화 10~11자리). 배차확정에는 차주 연락처가 필요합니다.",
    };
  }
  if (!name) {
    return {
      kind: "error",
      reason: "차주 이름을 찾지 못했습니다. 배차확정에는 차주 이름이 필요합니다.",
    };
  }

  return { kind: "ok", driver: { name, phone, vehiclePlate: plate }, unknownTokens: unknown };
}
