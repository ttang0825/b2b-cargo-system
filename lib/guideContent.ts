// 이용가이드 본문의 **유일한 정의처**.
//
// 화면은 둘이고 글은 여기 하나다.
//   /guide            공개 · 한 장 스크롤 — 계정을 막 받은 사람이 **순서대로** 읽는 자리
//   /customer/guide   포털 · 항목 선택   — 이미 쓰는 사람이 **필요한 것만** 찾는 자리
//
// 🔴 **본문을 화면 파일에 다시 적지 말 것.** PR #148 이 「두 벌이면 한쪽만 낡는다」며
//    페이지를 하나로 뒀던 걱정은 **없앤 것이 아니라 이렇게 푼 것이다** — 글은 한 곳에
//    두고 `scope` 로 어느 화면에 나갈지만 가른다.
//
// 🔴 **이 파일에 화면 마크업(JSX·className)을 넣지 말 것.** 넣는 순간 공개 화면 CSS 와
//    `.pv2-*`(포털 전용 스코프)가 한 파일에서 섞이고, 두 화면이 같은 마크업을 강제로
//    쓰게 된다. **그리는 일은 각 화면이 한다.**
//
// ── `lib/legal/*.ts` 와 같은 모양이다 ──────────────────────────────────────
// 순수 데이터 + 블록 유니온 + `**...**` 강조. 한 가지만 다르다: 법적 문서는 렌더러가
// 하나(`components/LegalDoc.tsx`)라 타입을 그 컴포넌트에 뒀지만, 이용가이드는 **렌더러가
// 둘이고 CSS 스코프가 서로 다르다.** 타입을 한쪽 렌더러에 두면 반대쪽 화면이 그 컴포넌트를
// import 하게 되어 두 화면이 한 파일에 묶인다 — 그래서 타입이 여기 있다.
//
// ⚠️ 강조 표기는 `**...**` 이고 **`/guide` 는 이것을 `<b>` 로 그린다**(법적 문서는
//    `<strong>`). 옮기기 전 화면이 `<b>` 였고 렌더링 결과를 그대로 두기 위한 것이다.

/** 어느 화면에 나가는 항목인가 */
export type GuideScope = "public" | "portal" | "both";

/** 「라벨 — 설명」 한 줄. 정의목록(dl)과 표(table)가 같이 쓴다 */
export type GuideRow = { label: string; desc: string };

export type GuideBlock =
  | { type: "p"; text: string }
  /** 번호가 붙는 절차 */
  | { type: "ol"; items: string[] }
  /** 주의·보충 상자. `plain` 이면 상자 없이 작은 글씨로만 */
  | { type: "note"; text: string; plain?: boolean }
  | { type: "dl"; rows: GuideRow[] }
  | { type: "table"; head: [string, string]; rows: GuideRow[] }
  | { type: "faq"; rows: { q: string; a: string }[] }
  /** 🔴 상태 알약은 **글자를 담지 않는다** — 라벨·색은 화면이 `lib/quoteStatusLabels.ts`·
   *  `lib/dispatchStage.ts` 에서 가져온다. 여기에 적으면 DB 값(`보류`·`실패`)이 이 파일에
   *  박히고, 라벨이 바뀔 때 안내만 조용히 낡는다. */
  | { type: "pills"; set: "quote" | "dispatch" }
  /** 설치 버튼 자리를 보여주는 CSS 도식(캡처 이미지가 아니다) */
  | { type: "mock"; buttonLabel: string }
  /** 전화 걸기 링크 */
  | { type: "tel"; label: string; number: string };

export type GuideItem = {
  /** 🔴 **URL 에 그대로 나간다**(`/customer/guide?topic=<id>`) — 바꾸면 밖에서 보낸
   *  링크가 깨진다. 영문 소문자·하이픈만 쓸 것. */
  id: string;
  /** 🔴 화면에 있는 문자열과 한 글자도 다르지 않게 — 두 화면의 제목이 곧 이것이다 */
  title: string;
  /** 제목 옆 작은 글씨(공개 화면 전용) */
  titleSub?: string;
  scope: GuideScope;
  /** 공개 화면에서 묶이는 자리. 없으면 자기 이름의 섹션 하나를 통째로 쓴다 */
  group?: GuideGroupKey;
  /** 공개 화면의 단계 번호(01~04) */
  step?: string;
  blocks: GuideBlock[];
};

export type GuideGroupKey = "start" | "status";

