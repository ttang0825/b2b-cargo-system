//
// 🔴 **2026-08-20 현재 아직 가입 전이다.** 미가입 상태에서 "보험 가입"이 화면에 보이면
// 허위·과장 광고이므로, 값이 채워질 때까지 `INSURANCE_ENABLED`로 막아둔다.
//
// ⚠️ 34차에 보험 언급을 고객 접점에서 **전부 제거**한 이력이 있다 — 당시 가입돼 있던 증권이
// 이사화물 운송주선업자 특별약관이라 **일반화물 사고가 담보되는지 자체가 확인되지 않았기**
// 때문이다. 약관 제19조(손해배상)는 보험과 무관하게 성립하도록 짜여 있으므로, 보험을 다시
// 노출하는 것은 **가입이 끝나고 담보 범위가 확인된 뒤**의 별도 판단이다.
//
// ── 이 파일을 쓰는 규칙(13차에서 UI가 들어올 때 지킬 것) ──────────────────────────
// 1. `INSURANCE_ENABLED`가 false면 보험 블록을 **DOM에 아예 렌더링하지 않는다.**
//    `visibility: hidden`이나 `display: none`이 아니라 **조건부 렌더링**이어야 한다 —
//    숨기기만 하면 페이지 소스에는 남아서 검색·스크래핑에 잡힌다.
// 2. **보험 문구를 컴포넌트에 하드코딩하지 않는다.** 반드시 이 파일만 참조할 것.
// 3. **히어로 신뢰줄 4번째와 안전·책임 섹션, 두 곳을 이 플래그 하나로 제어한다.**
//    별도 플래그를 만들지 말 것 — 한쪽만 켜지는 사고를 막기 위함이다.
//
// ⚠️ **12차 시점에는 이 상수를 참조하는 UI가 하나도 없다**(의도된 것, 13차 범위).
// 파일만 먼저 만들어 13차가 UI에만 집중할 수 있게 해둔 것이다.

/** 적재물배상책임보험 가입 완료 시 true. false면 관련 UI는 렌더링되지 않는다. */
