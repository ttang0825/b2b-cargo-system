export const INSURANCE_EXCLUSION_NOTE = "";

// 위 값들이 아직 비어 있음을 나타내는 자리표시자 플래그.
// next.config.mjs가 빌드·서버 기동 시 이 파일을 텍스트로 읽어 `= true`이면 콘솔에 경고를
// 출력한다(빌드를 실패시키지는 않음 — 26·29·30차와 동일한 방식).
//
// 🔴 **반드시 리터럴 `true`/`false`로 둘 것.** 경고 로직이 `= true` 문자열을 정규식으로
// 찾으므로, 계산식이나 다른 변수로 유도하면 경고가 조용히 동작하지 않는다.
// 🔴 `INSURANCE_ENABLED`를 경고 대상으로 쓸 수 없어서 이 플래그를 따로 둔 것이다 —
// 그 값은 미가입 상태에서 `false`라 `= true` 검사에 걸리지 않는다.
// 가입이 끝나면 위 값들을 채우고 **이 플래그를 false로, `INSURANCE_ENABLED`를 true로**
