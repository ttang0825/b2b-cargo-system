/**
 * DB 에서 받은 옵션 목록을 `QUOTE_BODY_TYPES` 순서로 정렬한다.
 *
 * 🔴 **이 배열에 없는 옵션을 버리지 말 것** — 담당자가 `/admin/rates` 에서 행을 넣었는데
 *    코드에 이름이 없다는 이유로 드롭다운에서 사라지면, 값은 DB 에 있는데 아무도 고를 수
 *    없는 상태가 된다. 모르는 것은 **맨 뒤에 붙인다.**
 */
export function orderBodyTypes(options: readonly string[]): string[] {
  const rank = new Map<string, number>(QUOTE_BODY_TYPES.map((t, i) => [t, i]));
  const known = options.filter((o) => rank.has(o)).sort((a, b) => rank.get(a)! - rank.get(b)!);
  const unknown = options.filter((o) => !rank.has(o));
  return [...known, ...unknown];
}
