// 차량형태(차종) — 유일 정의처. PR #103 리뷰 3번(원콜 오더 차종 참고)으로 신설.
//
// ══ 🔴 두 목록이 있고, 일부러 다르다 ═══════════════════════════════════════
//
//   QUOTE_BODY_TYPES   견적 선택지 — `/customer/request` · `/admin/quotes` 드롭다운
//                      🔴 **`rate_surcharges` 의 `차량형태` 카테고리와 완전일치해야 한다**
//   DRIVER_BODY_TYPES  차주 보유차량 · 화주 CRM 추천차량 — 견적 계산과 무관
//
// 🔴 **둘을 합치지 말 것.** 차주는 크레인·렉카·사다리차를 보유할 수 있지만(실측:
//    `vehicles.body_type` 에 `사다리차` 1건이 있다) 화주가 견적에서 고르는 항목은
//    아니다. 반대로 조합형(`카고/윙`)은 견적 선택지이지 한 대의 차량 사양이 아니다.
//
// ══ 🔴 새 차종을 추가할 때 반드시 함께 할 것 ═══════════════════════════════
//
//   ① 이 파일의 `QUOTE_BODY_TYPES` 에 추가
//   ② `rate_surcharges` 에 **같은 이름의 행**을 넣는 마이그레이션
//
//   둘 중 하나만 하면 조용히 어긋난다 —
//     · 코드만: 견적 계산이 `option_name` **문자열 완전일치**로 매칭한 뒤 못 찾으면
//       `continue` 한다. **예외도 경고도 없이 가산만 빠진다**(48차 `도크` 와 같은 함정)
//     · DB만: 드롭다운 맨 뒤에 붙긴 하지만(아래 `orderBodyTypes` 참고) 순서가 어색해진다
//
// ══ ⚠️ 원콜 23종 중 일부러 뺀 것 (`차종무관` 은 리뷰에서 추가됐다) ═══════════════════════════════════════════
//
//   🔴 추레라·다마스·라보  **차량형태가 아니라 차급이다.** 넣으면 "1톤 다마스" 같은
//                        조합이 생기고, `rate_distance_tiers` 에 그 차급 행이 없어
//                        "선택하신 톤수에 해당하는 운임기준이 없습니다"(15차 문구)가 뜬다.
//                        차급 확장은 `VEHICLE_TYPES_ALL` + 운임 15구간 행이 따라오는
//                        별도 차수다(52차 `2026-08-26_rate_8t_15t.sql` 이 본보기)
//
// ⚠️ 원콜은 `탑` 이라 부르지만 **우리는 `탑차` 를 유지한다** — 담당자가 실제로 쓰는 말이
//    "탑차"다(`companies.recommended_vehicle` 539건이 "1톤 탑차·2.5톤 탑차" 형태).

/**
 * 견적 선택지. 🔴 **표시 순서가 이 배열 순서다** — 가산이 낮은 순(≒ 흔한 순)으로 두었다.
 * 🔴 `rate_surcharges` 의 `차량형태` 행과 이름이 하나도 어긋나면 안 된다.
 */
export const QUOTE_BODY_TYPES = [
  "카고",
  "카고/윙",
  "호로",
  "탑차",
  "윙바디/탑",
  "윙바디",
  "윙플러스",
  "리프트",
  "카고리프트",
  "초장축",
  "호로리프트",
  "탑리프트",
  "냉장탑",
  "리프트윙",
  "냉장윙",
  "냉동탑",
  "냉동탑리프트",
  "냉장윙리프트",
  "무진동",
  // 🔴 맨 뒤 둘은 고정이다 — 특정 차종을 가리키지 않는 "받침" 두 개이고,
  //    뜻이 정반대라 **하나로 합치지 말 것**(PR #103 리뷰에서 확정).
  //      특수/협의  위 목록에 없는 차가 필요하다 → 배차가 **어려워진다**
  //      차종무관   아무 차나 괜찮다           → 배차가 **쉬워진다**
  //    그래서 순서도 이대로다 — `차종무관` 이 **제일 하단**이다.
  "특수/협의",
  "차종무관",
] as const;

/**
 * 차주 보유차량 · 화주 CRM 추천차량.
 * 🔴 견적 선택지에 없는 넷(크레인·렉카·사다리차·트레일러)을 빼지 말 것 —
 *    차주가 실제로 보유할 수 있는 차량이고 저장된 값도 있다.
 */
export const DRIVER_BODY_TYPES = [
  // 🔴 `특수/협의`·`차종무관` 은 **한 대의 차량 사양이 아니라 요청의 성격**이다.
  //    차주 보유차량이 "차종무관" 일 수는 없다.
  ...QUOTE_BODY_TYPES.filter((t) => t !== "특수/협의" && t !== "차종무관"),
  "크레인",
  "렉카",
  "사다리차",
  "트레일러",
  "기타/협의",
] as const;

/**
 * DB 에서 받은 옵션 목록을 `QUOTE_BODY_TYPES` 순서로 정렬한다.
 *
 * 🔴 **이 배열에 없는 옵션을 버리지 말 것** — 담당자가 `/admin/rates` 에서 행을 넣었는데
 *    코드에 이름이 없다는 이유로 드롭다운에서 사라지면, 값은 DB 에 있는데 아무도 고를 수
 *    없는 상태가 된다. 모르는 것은 **맨 뒤에 붙인다.**
 */
export function orderBodyTypes(options: readonly string[]): string[] {
  const rank = new Map<string, number>(QUOTE_BODY_TYPES.map((t, i) => [t, i]));
  const known = options.filter((o) => rank.has(o)).sort((a, b) => rank.get(a)! - rank.get(b)!);
  const unknown = options.filter((o) => !rank.has(o));
  return [...known, ...unknown];
}
