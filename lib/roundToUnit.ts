import { DAMAS_LABO_ROUND_UNIT, DEFAULT_ROUND_UNIT, SMALL_VAN_VEHICLE_TYPES } from "./constants";

/** 그 차급의 격자 단위 — 다마스·라보 5,000 / 나머지 10,000 */
export function roundUnitOf(vehicleType: string | null | undefined): number {
  return vehicleType && (SMALL_VAN_VEHICLE_TYPES as readonly string[]).includes(vehicleType)
    ? DAMAS_LABO_ROUND_UNIT
    : DEFAULT_ROUND_UNIT;
}

/**
 * 금액을 그 차급의 격자에 올린다.
 *
 * 🔴 **개별 가산 줄이 아니라 「소계」에 건다** — 줄마다 반올림하면 윙바디 10,000 은
 *    그대로지만 왕복 요율 같은 작은 값이 통째로 올라가 **과다 청구**가 됩니다.
 * 🔴 **대기료·경유지비도 같은 소계 안에서** 함께 반올림합니다 — 밖에 두면 최종금액이
 *    만원에서 벗어납니다.
 *
 * ⚠️ 0 은 0 그대로입니다(가산을 안 고른 견적의 출력이 종전과 한 글자도 같아야 합니다).
 * ⚠️ 음수도 부호를 지키며 반올림합니다 — 지금 이 함수에 음수가 들어오는 호출부는
 *    없지만(가산은 전부 양수, 혼적 할인액은 양수로 넘어옵니다), 조용히 0 으로
 *    무너지지 않게 해 둡니다.
 */
export function roundToUnit(amount: number, vehicleType: string | null | undefined): number {
  if (!Number.isFinite(amount) || amount === 0) return 0;
  const unit = roundUnitOf(vehicleType);
  return Math.round(amount / unit) * unit;
}
